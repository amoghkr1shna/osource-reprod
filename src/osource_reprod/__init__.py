def hello_world() -> str:
    """Return a greeting message.

    Returns:
        str: A friendly greeting
    """
    return "Hello, World!"


def add_numbers(a: int, b: int) -> int:
    """Add two numbers together.

    Args:
        a: First number
        b: Second number

    Returns:
        int: Sum of the two numbers
    """
    return a + b
